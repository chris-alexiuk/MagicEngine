/** The parameters each kind of node carries in a card's abilities and keywords: type → the fields used. */
export function nodeFields(card: CardDef): Map<string, Set<string>> {
  const out = new Map<string, Set<string>>();
  const walk = (n: unknown): void => {
    if (Array.isArray(n)) {
      for (const v of n) walk(v);
      return;
    }
    if (!n || typeof n !== 'object') return;
    const type = (n as { type?: unknown }).type;
    const fields = typeof type === 'string' ? (out.get(type) ?? out.set(type, new Set()).get(type)!) : null;
    for (const [k, v] of Object.entries(n)) {
      if (fields && k !== 'type') fields.add(k);
      walk(v);
    }
  };
  for (const face of card.faces) {
    walk(face.abilities);
    walk(face.keywords);
  }
  return out;
}

/** The parameters in these cards that NODE_FIELDS doesn't declare, as "type.field". */
export function undeclaredFields(cards: Iterable<CardDef>): string[] {
  const out = new Set<string>();
  for (const card of cards) {
    for (const [type, fields] of nodeFields(card)) for (const f of fields) if (!NODE_FIELDS[type]?.includes(f)) out.add(`${type}.${f}`);
  }
  return [...out].sort();
}
