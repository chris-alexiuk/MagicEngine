import type { RulesDoc } from './parse.js';

/**
 * Keyword definitions from CR 702: most keyword abilities are defined as a
 * reminder-style sentence, e.g. 702.108a: “Prowess” means “Whenever you cast a
 * noncreature spell, this creature gets +1/+1 until end of turn.” The compiler
 * parses those sentences with the same grammar as card text, so a keyword works
 * as soon as the grammar can read its definition.
 */
export interface KeywordDefinition {
  /** The rule the definition comes from, e.g. "702.108a". */
  rule: string;
  /** The keyword as written in the definition, with parameters: "Afterlife N", "Cycling [cost]". */
  pattern: string;
  /** One sentence per ability the keyword represents. */
  meaning: string[];
  /** Zone the ability functions in, when it isn't the battlefield ("functions only while … in a player’s hand"). */
  zone?: 'hand' | 'graveyard';
  /**
   * What the keyword means on an instant or sorcery spell, where the rules say that apart from what it means on a
   * permanent (ascend: 702.131a a spell ability, 702.131b a static ability).
   */
  spell?: { rule: string; meaning: string[] };
}

function slug(name: string): string {
  return name
    .replace(/\[type\]/i, 'type')
    .replace(/\s*(?:\[[^\]]+\]|\bN\b|—.*)\s*/g, ' ')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

const ZONE = /functions (?:only )?while the card with [\w ]+ is in (?:a player's|your|a) (hand|graveyard)/;

/**
 * A keyword action (CR 701) the rules define by what it means, the way they define keywords: 701.70a “Recruit” means
 * “Draw a card, then discard a card. If you discarded a nonland card this way, create a 1/1 white Human Soldier creature
 * token.”; 701.71a To empower Jace N means “…”. The compiler reads the meaning as it reads card text, so a card that says
 * "recruit" works as soon as the grammar can read that sentence.
 */
export interface ActionDefinition {
  /** The rule the definition comes from, e.g. "701.70a". */
  rule: string;
  /** The action as written in the definition, with parameters: "Recruit", "empower Jace N", "amass [subtype] N". */
  pattern: string;
  /** What doing it means: instructions, as a card would print them. */
  meaning: string;
}

export function extractActionDefinitions(doc: RulesDoc): Record<string, ActionDefinition> {
  const out: Record<string, ActionDefinition> = {};
  for (const [id, rule] of Object.entries(doc.rules)) {
    if (!/^701\.\d+[a-z]$/.test(id)) continue;
    const text = rule.text.replace(/’/g, "'").replace(/\s*\([^()]*\)/g, '');
    // “Recruit” means “…” — or To empower Jace N means “…”, To “scry N” means to … (no quoted meaning: not one of these).
    const m = /^(?:“([^”\[]+)”|To ([a-z][^“”]*?)) means (“[^”]+”)(?: See rule [\d.]+[a-z]?(?:, “[^”]+”)?\.?)?$/.exec(text);
    if (!m) continue;
    const pattern = (m[1] ?? m[2])!.trim();
    const key = slug(pattern);
    const meaning = m[3]!.slice(1, -1).trim();
    if (!key || out[key] || !/[.!]$/.test(meaning)) continue;
    out[key] = { rule: id, pattern, meaning };
  }
  return out;
}

/**
 * The names the rules give a section of keyword actions (CR 701, "Recruit") or keyword abilities (CR 702, "Storied"),
 * lower-case: every word of that kind the rules know. A word that isn't among them is one the rules don't define yet
 * — a set being previewed — and only such a word is read from a card's reminder text.
 */
export function sectionNames(doc: RulesDoc, chapter: '701' | '702'): string[] {
  const out: string[] = [];
  for (const [id, rule] of Object.entries(doc.rules)) {
    if (!new RegExp(`^${chapter}\\.\\d+$`).test(id) || id === `${chapter}.1`) continue;
    const name = rule.text.replace(/’/g, "'").trim().toLowerCase();
    if (name && name.length < 40 && !/[.“”]/.test(name)) out.push(name);
  }
  return out.sort();
}

export function actionDefinitionsModule(defs: Record<string, ActionDefinition>, effectiveDate: string | null | undefined, names: string[] = []): string {
  const entries = Object.entries(defs)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`)
    .join('\n');
  return `// Generated by \`pnpm rules:keywords\` from docs/rules/rules.json (rules effective ${effectiveDate ?? 'unknown'}).
// Do not edit by hand. Source: the keyword actions CR 701 defines by a quoted meaning.

export interface ActionDefinition {
  rule: string;
  pattern: string;
  meaning: string;
}

export const ACTION_DEFINITIONS: Record<string, ActionDefinition> = {
${entries}
};

/** Every keyword action the rules name (the sections of CR 701), lower-case. */
export const RULES_ACTIONS: readonly string[] = ${JSON.stringify(names)};
`;
}

export function extractKeywordDefinitions(doc: RulesDoc): Record<string, KeywordDefinition> {
  const out: Record<string, KeywordDefinition> = {};
  // A zone stated anywhere in a keyword's section applies to its variants too (702.29a covers typecycling, 702.29e).
  const sectionZone: Record<string, 'hand' | 'graveyard'> = {};
  for (const [id, rule] of Object.entries(doc.rules)) {
    const z = /^(702\.\d+)[a-z]$/.exec(id) && ZONE.exec(rule.text.replace(/’/g, "'"));
    if (z) sectionZone[id.replace(/[a-z]$/, '')] = z[1] as 'hand' | 'graveyard';
  }
  for (const [id, rule] of Object.entries(doc.rules)) {
    if (!/^702\.\d+[a-z]$/.test(id)) continue;
    // Drop parentheticals ("(See rule 509, “Declare Blockers Step.”)", "(as in “mountaincycling”)").
    const text = rule.text.replace(/’/g, "'").replace(/\s*\([^()]*\)/g, '');
    // “Afterlife N” means “…” — or, unquoted, Ward [cost] means “…”.
    const m = /(?:“([^”]+)”|\b(Ward \[cost\])) means (“.+)$/.exec(text);
    if (!m) continue;
    const pattern = (m[1] ?? m[2])!.replace(/'/g, '’');
    const key = slug(pattern);
    if (!key || out[key]) continue;
    const meaning = [...m[3]!.matchAll(/“([^”]+)”/g)].map((x) => {
      const s = x[1]!.trim().replace(/,$/, '');
      return /[.!]$/.test(s) ? s : `${s}.`;
    });
    if (!meaning.length) continue;
    const def: KeywordDefinition = { rule: id, pattern, meaning };
    const zone = sectionZone[id.replace(/[a-z]$/, '')];
    if (zone) def.zone = zone;
    out[key] = def;
  }
  // A keyword defined by a sentence about it and then "It means “…”": 702.195a Storied is a static ability. It means
  // “Any time you control three or more permanents … you have an enduring story for the rest of the game.” Some are
  // defined once for a permanent and once for an instant or sorcery spell (702.131a–b, ascend).
  for (const [id, rule] of Object.entries(doc.rules)) {
    if (!/^702\.\d+[a-z]$/.test(id)) continue;
    const text = rule.text.replace(/’/g, "'").replace(/\s*\([^()]*\)/g, '');
    const m = /^([A-Z][A-Za-z' -]*?)( on a permanent| on an instant or sorcery spell)? (?:is|represents) an? [a-z ]*ability[^.“”]*\. It means (“[^”]+”)$/.exec(text);
    if (!m) continue;
    const key = slug(m[1]!);
    const meaning = [m[3]!.slice(1, -1).trim()];
    if (!key || !/[.!]$/.test(meaning[0]!)) continue;
    const onSpell = m[2] === ' on an instant or sorcery spell';
    const have = out[key];
    if (onSpell) {
      if (have && !have.spell) have.spell = { rule: id, meaning };
      else if (!have) out[key] = { rule: id, pattern: m[1]!, meaning: [], spell: { rule: id, meaning } };
    } else if (!have) out[key] = { rule: id, pattern: m[1]!, meaning };
    else if (!have.meaning.length) Object.assign(have, { rule: id, meaning });
  }
  return out;
}

export function keywordDefinitionsModule(defs: Record<string, KeywordDefinition>, effectiveDate: string | null | undefined, names: string[] = []): string {
  const entries = Object.entries(defs)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`)
    .join('\n');
  return `// Generated by \`pnpm rules:keywords\` from docs/rules/rules.json (rules effective ${effectiveDate ?? 'unknown'}).
// Do not edit by hand. Source: the definitions in CR 702.

export interface KeywordDefinition {
  rule: string;
  pattern: string;
  meaning: string[];
  zone?: 'hand' | 'graveyard';
  /** What the keyword means on an instant or sorcery spell, where the rules say that apart. */
  spell?: { rule: string; meaning: string[] };
}

export const KEYWORD_DEFINITIONS: Record<string, KeywordDefinition> = {
${entries}
};

/** Every keyword ability the rules name (the sections of CR 702), lower-case. */
export const RULES_KEYWORDS: readonly string[] = ${JSON.stringify(names)};
`;
}
