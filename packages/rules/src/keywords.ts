import type { RulesDoc } from './parse.js';

/**
 * Keyword definitions from CR 702: most keyword abilities are defined as a
 * reminder-style sentence, e.g. 702.108a: “Prowess” means “Whenever you cast a
 * noncreature spell, this creature gets +1/+1 until end of turn.” The compiler
 * parses those sentences with the same grammar as card text, so a keyword works
 * as soon as the grammar can read its definition.
 */
export interface KeywordDefinition {
  /** The rule the definition comes from, e.g. "702.108a". */
  rule: string;
  /** The keyword as written in the definition, with parameters: "Afterlife N", "Cycling [cost]". */
  pattern: string;
  /** One sentence per ability the keyword represents. */
  meaning: string[];
  /** Zone the ability functions in, when it isn't the battlefield ("functions only while … in a player’s hand"). */
  zone?: 'hand' | 'graveyard';
}

function slug(name: string): string {
  return name
    .replace(/\[type\]/i, 'type')
    .replace(/\s*(?:\[[^\]]+\]|\bN\b|—.*)\s*/g, ' ')
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

const ZONE = /functions (?:only )?while the card with [\w ]+ is in (?:a player's|your|a) (hand|graveyard)/;

export function extractKeywordDefinitions(doc: RulesDoc): Record<string, KeywordDefinition> {
  const out: Record<string, KeywordDefinition> = {};
  // A zone stated anywhere in a keyword's section applies to its variants too (702.29a covers typecycling, 702.29e).
  const sectionZone: Record<string, 'hand' | 'graveyard'> = {};
  for (const [id, rule] of Object.entries(doc.rules)) {
    const z = /^(702\.\d+)[a-z]$/.exec(id) && ZONE.exec(rule.text.replace(/’/g, "'"));
    if (z) sectionZone[id.replace(/[a-z]$/, '')] = z[1] as 'hand' | 'graveyard';
  }
  for (const [id, rule] of Object.entries(doc.rules)) {
    if (!/^702\.\d+[a-z]$/.test(id)) continue;
    // Drop parentheticals ("(See rule 509, “Declare Blockers Step.”)", "(as in “mountaincycling”)").
    const text = rule.text.replace(/’/g, "'").replace(/\s*\([^()]*\)/g, '');
    // “Afterlife N” means “…” — or, unquoted, Ward [cost] means “…”.
    const m = /(?:“([^”]+)”|\b(Ward \[cost\])) means (“.+)$/.exec(text);
    if (!m) continue;
    const pattern = (m[1] ?? m[2])!.replace(/'/g, '’');
    const key = slug(pattern);
    if (!key || out[key]) continue;
    const meaning = [...m[3]!.matchAll(/“([^”]+)”/g)].map((x) => {
      const s = x[1]!.trim().replace(/,$/, '');
      return /[.!]$/.test(s) ? s : `${s}.`;
    });
    if (!meaning.length) continue;
    const def: KeywordDefinition = { rule: id, pattern, meaning };
    const zone = sectionZone[id.replace(/[a-z]$/, '')];
    if (zone) def.zone = zone;
    out[key] = def;
  }
  return out;
}

export function keywordDefinitionsModule(defs: Record<string, KeywordDefinition>, effectiveDate: string | null | undefined): string {
  const entries = Object.entries(defs)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, d]) => `  ${JSON.stringify(k)}: ${JSON.stringify(d)},`)
    .join('\n');
  return `// Generated by \`pnpm rules:keywords\` from docs/rules/rules.json (rules effective ${effectiveDate ?? 'unknown'}).
// Do not edit by hand. Source: the definitions in CR 702.

export interface KeywordDefinition {
  rule: string;
  pattern: string;
  meaning: string[];
  zone?: 'hand' | 'graveyard';
}

export const KEYWORD_DEFINITIONS: Record<string, KeywordDefinition> = {
${entries}
};
`;
}
