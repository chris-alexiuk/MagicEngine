import type { RulesDoc } from './parse.js';
import { sectionOf } from './parse.js';

/**
 * Rule citations in source are written "CR 117.3a" (one number per "CR").
 * Code citations mean "implemented here"; test citations mean "checked here".
 */
export const CITATION = /\bCR\s+(\d{3}(?:\.\d+[a-z]*)?)\b/g;

export interface Citation {
  rule: string;
  file: string;
  line: number;
  kind: 'code' | 'test';
}

export function findCitations(source: string, file: string, kind: Citation['kind']): Citation[] {
  const out: Citation[] = [];
  source.split('\n').forEach((text, i) => {
    for (const m of text.matchAll(CITATION)) out.push({ rule: m[1]!, file, line: i + 1, kind });
  });
  return out;
}

export interface TraceRow {
  rule: string;
  code: Citation[];
  tests: Citation[];
}

export interface TraceReport {
  effectiveDate?: string;
  rows: TraceRow[];
  unknown: Citation[];
  bySection: { section: string; title: string; total: number; implemented: number; tested: number }[];
}

export function buildTrace(doc: RulesDoc | null, citations: Citation[]): TraceReport {
  const rows = new Map<string, TraceRow>();
  const unknown: Citation[] = [];
  for (const c of citations) {
    if (doc && !doc.rules[c.rule]) {
      unknown.push(c);
      continue;
    }
    const row = rows.get(c.rule) ?? { rule: c.rule, code: [], tests: [] };
    (c.kind === 'code' ? row.code : row.tests).push(c);
    rows.set(c.rule, row);
  }

  const sorted = [...rows.values()].sort((a, b) => compareRuleIds(a.rule, b.rule));
  const bySection: TraceReport['bySection'] = [];
  if (doc) {
    for (const chapter of doc.chapters) {
      for (const section of chapter.sections) {
        const inSection = sorted.filter((r) => sectionOf(r.rule) === section);
        if (inSection.length === 0) continue;
        const total = Object.keys(doc.rules).filter((id) => sectionOf(id) === section && id !== section).length;
        bySection.push({
          section,
          title: doc.rules[section]?.text ?? '',
          total,
          implemented: inSection.filter((r) => r.code.length > 0).length,
          tested: inSection.filter((r) => r.tests.length > 0).length,
        });
      }
    }
  }
  return { ...(doc?.effectiveDate ? { effectiveDate: doc.effectiveDate } : {}), rows: sorted, unknown, bySection };
}

/** Orders "100.1a" < "100.2" < "100.10" < "101". */
export function compareRuleIds(a: string, b: string): number {
  const parse = (id: string) => {
    const m = /^(\d{3})(?:\.(\d+)([a-z]*))?$/.exec(id);
    return m ? [Number(m[1]), Number(m[2] ?? -1), m[3] ?? ''] as const : ([0, 0, id] as const);
  };
  const [as, an, al] = parse(a);
  const [bs, bn, bl] = parse(b);
  return as - bs || an - bn || (al.length - bl.length) || al.localeCompare(bl);
}

export function traceMarkdown(report: TraceReport, doc: RulesDoc | null): string {
  const snippet = (id: string) => {
    const text = doc?.rules[id]?.text.split('\n')[0] ?? '';
    return text.length > 90 ? `${text.slice(0, 87)}…` : text;
  };
  const where = (cs: Citation[]) =>
    cs.length === 0 ? '' : [...new Set(cs.map((c) => `${c.file.split('/').pop()}:${c.line}`))].slice(0, 3).join(', ');
  const lines = [
    '# Comprehensive Rules trace',
    '',
    report.effectiveDate ? `Against the rules effective ${report.effectiveDate}.` : 'Rules text not available yet; citations are unchecked.',
    'Generated by `pnpm rules:trace` from `CR x.y` citations in the engine. Do not edit by hand.',
    '',
    `${report.rows.filter((r) => r.code.length).length} rules implemented, ${report.rows.filter((r) => r.tests.length).length} tested.`,
    '',
  ];
  if (report.unknown.length) {
    lines.push('## Citations of rules that do not exist', '');
    for (const c of report.unknown) lines.push(`- CR ${c.rule} at ${c.file}:${c.line}`);
    lines.push('');
  }
  if (report.bySection.length) {
    lines.push('## By section', '', '| Section | Rules | Implemented | Tested |', '|---|---:|---:|---:|');
    for (const s of report.bySection) lines.push(`| ${s.section}. ${s.title} | ${s.total} | ${s.implemented} | ${s.tested} |`);
    lines.push('');
  }
  lines.push('## Cited rules', '', '| Rule | Text | Code | Tests |', '|---|---|---|---|');
  for (const r of report.rows) {
    lines.push(`| ${r.rule} | ${snippet(r.rule).replace(/\|/g, '\\|')} | ${where(r.code)} | ${where(r.tests)} |`);
  }
  lines.push('');
  return lines.join('\n');
}
