import type { RulesDoc } from './parse.js';

/** CR 205.3g–m: the rules that list each card type's subtypes. */
const SUBTYPE_RULES: Record<string, string> = {
  artifact: '205.3g',
  enchantment: '205.3h',
  land: '205.3i',
  planeswalker: '205.3j',
  spell: '205.3k',
  creature: '205.3m',
};

export type SubtypeLists = Record<keyof typeof SUBTYPE_RULES, string[]>;

/**
 * Pulls the subtype lists out of the rules text, e.g. "The artifact types are
 * Attraction (see rule 717), Blood, … and Vehicle." → ["Attraction", "Blood", …].
 */
export function extractSubtypes(doc: RulesDoc): SubtypeLists {
  const out = {} as SubtypeLists;
  for (const [kind, id] of Object.entries(SUBTYPE_RULES)) {
    const text = doc.rules[id]?.text;
    if (!text) throw new Error(`rule ${id} is missing from rules.json`);
    // The list follows "are" (creature types: "All other creature types are one word long:").
    const m = /(?:The \w+ types are|one word long:)\s+(.+?)\.(?:\s|$)/.exec(text);
    if (!m) throw new Error(`can't find the list in rule ${id}`);
    const items = m[1]!
      .replace(/\s*\(see rules? [^)]*\)/g, '')
      .split(/,\s*(?:and\s+)?|\s+and\s+/)
      .map((s) => s.trim())
      .filter(Boolean);
    // CR 205.3m: "One creature type is two words long: Time Lord."
    if (kind === 'creature') {
      const two = /two words long:\s+([^.]+)\./.exec(text);
      if (two) items.push(two[1]!.trim());
    }
    out[kind as keyof SubtypeLists] = [...new Set(items)].sort();
  }
  return out;
}

export function subtypesModule(lists: SubtypeLists, effectiveDate: string | null | undefined): string {
  const body = Object.entries(lists)
    .map(([kind, items]) => `  ${kind}: ${JSON.stringify(items)},`)
    .join('\n');
  return `// Generated by \`pnpm rules:subtypes\` from docs/rules/rules.json (rules effective ${effectiveDate ?? 'unknown'}).
// Do not edit by hand. Source: CR 205.3g–205.3m.

export const SUBTYPES: Record<'artifact' | 'enchantment' | 'land' | 'planeswalker' | 'spell' | 'creature', readonly string[]> = {
${body}
};
`;
}
